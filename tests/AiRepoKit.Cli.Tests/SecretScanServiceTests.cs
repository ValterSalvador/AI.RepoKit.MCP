using System.Text;
using System.Text.Json;
using AiRepoKit.Cli.Services.SecretScan;
using Xunit;

namespace AiRepoKit.Cli.Tests;

public sealed class SecretScanServiceTests
{
    [Fact]
    public void Run_EmptyRepositoryWritesSafeReport()
    {
        using TempRepo repo =
            new();

        SecretScanRunResult result =
            RunSuccess(repo);

        Assert.False(
            result.Report!.SecretsExposed);

        Assert.False(
            result.Report.SecretValuesReturned);

        Assert.True(
            result.Report.RedactedOnly);

        Assert.Equal(
            0,
            result.Report.FindingCount);

        Assert.Empty(
            result.Report.Findings);

        Assert.True(
            File.Exists(
                repo.ReportPath));
    }

    [Fact]
    public void Run_DetectsAllLegacyPatternFamiliesCaseInsensitively()
    {
        using TempRepo repo =
            new();

        repo.WriteText(
            "patterns.txt",
            """
            PASSWORD = one
            PaSsWd: two
            PWD=three
            SeCrEt:four
            TOKEN=five
            API_KEY=six
            api-key:seven
            ConnectionString = eight
            """);

        SecretScanRunResult result =
            RunSuccess(repo);

        Assert.Equal(
            8,
            result.Report!.FindingCount);

        Assert.Equal(
            8,
            result.Report.Findings.Count);
    }

