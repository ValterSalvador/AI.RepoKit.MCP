    [Fact]
    public void Run_MissingRepositoryReturnsFailureAndDoesNotWriteReport()
    {
        string missing =
            Path.Combine(
                Path.GetTempPath(),
                "airepo_secret_scan_missing_" +
                Guid.NewGuid()
                    .ToString("N"));

        SecretScanRunResult result =
            new SecretScanService()
                .Run(
                    missing);

        Assert.False(
