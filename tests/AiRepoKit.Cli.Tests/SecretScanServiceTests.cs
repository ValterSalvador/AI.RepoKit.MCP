    [Fact]
    public void Run_NormalizesAndSortsRelativePathsDeterministically()
    {
        using TempRepo repo =
            new();

        repo.WriteText(
            "z/Z.txt",
            "token=z");

        repo.WriteText(
            "a/A.txt",
            "token=a");

        SecretScanRunResult result =
            RunSuccess(repo);

        Assert.Equal(
            [
                "a/A.txt",
                "z/Z.txt"
            ],
            result.Report!
                .Findings
                .Select(
                    finding =>
                        finding.File));

        Assert.All(
            result.Report.Findings,
            finding =>
                Assert.DoesNotContain(
                    '\\',
                    finding.File));
    }

    [Fact]
    public void Run_WritesExpectedJsonContract()
    {
        using TempRepo repo =
            new();

        repo.WriteText(
            "scan.txt",
            "token=value");

        RunSuccess(repo);

        using JsonDocument document =
            JsonDocument.Parse(
                File.ReadAllText(
                    repo.ReportPath));

        JsonElement root =
            document.RootElement;

        Assert.False(
            root.GetProperty(
                "SecretsExposed")
                .GetBoolean());

        Assert.False(
            root.GetProperty(
                "SecretValuesReturned")
                .GetBoolean());

        Assert.True(
            root.GetProperty(
                "RedactedOnly")
                .GetBoolean());

        Assert.Equal(
            1,
            root.GetProperty(
                "FindingCount")
                .GetInt32());

        JsonElement finding =
            root.GetProperty(
                "Findings")[0];

        Assert.Equal(
            "scan.txt",
            finding.GetProperty(
                "file")
                .GetString());

        Assert.Equal(
            "SecretPattern",
            finding.GetProperty(
                "category")
                .GetString());

        Assert.Equal(
            "High",
            finding.GetProperty(
                "severity")
                .GetString());

        Assert.Equal(
            "<redacted>",
            finding.GetProperty(
                "preview")
                .GetString());

        Assert.False(
            finding.TryGetProperty(
                "File",
                out _));
    }

