    }

    private static SecretScanRunResult RunSuccess(
        TempRepo repo)
    {
        SecretScanRunResult result =
            new SecretScanService()
                .Run(
                    repo.Root);

        Assert.True(
            result.IsSuccess,
            result.ErrorMessage);

        Assert.NotNull(
            result.Report);

        return result;
    }

    private sealed class TempRepo :
        IDisposable
    {
        public TempRepo()
        {
            Root =
                Path.Combine(
                    Path.GetTempPath(),
                    "airepo_secret_scan_" +
                    Guid.NewGuid()
                        .ToString("N"));

            Directory.CreateDirectory(
                Root);
        }

        public string Root { get; }

        public string ReportPath =>
            GetPath(
                SecretScanService.ReportRelativePath);

        public string GetPath(
            string relativePath)
        {
            return Path.Combine(
                Root,
                relativePath.Replace(
                    '/',
                    Path.DirectorySeparatorChar));
        }

        public void WriteText(
            string relativePath,
            string content)
        {
            string path =
                GetPath(
                    relativePath);

            string? directory =
                Path.GetDirectoryName(
                    path);

            if (!string.IsNullOrWhiteSpace(
                    directory))
            {
                Directory.CreateDirectory(
                    directory);
            }

            File.WriteAllText(
                path,
                content,
                new UTF8Encoding(
                    encoderShouldEmitUTF8Identifier: false));
        }

        public void WriteSizedAsciiFile(
            string relativePath,
            int byteCount,
            string prefix)
        {
            if (prefix.Length > byteCount)
            {
                throw new ArgumentOutOfRangeException(
                    nameof(byteCount));
            }

            WriteText(
                relativePath,
                prefix +
                new string(
                    'x',
                    byteCount -
                    prefix.Length));
        }

        public void Dispose()
        {
            if (!Directory.Exists(
                    Root))
            {
                return;
            }

            try
            {
                Directory.Delete(
                    Root,
                    recursive: true);
            }
            catch
            {
            }
        }
    }
