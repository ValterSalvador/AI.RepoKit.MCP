    [Fact]
    public void Run_NeverEmitsMatchedSecretValues()
    {
        using TempRepo repo =
            new();

        const string secretValue =
            "ULTRA_SECRET_VALUE_123456789";

        repo.WriteText(
            "safe-to-scan.txt",
            "token=" + secretValue);

        SecretScanRunResult result =
            RunSuccess(repo);

        string json =
            File.ReadAllText(
                repo.ReportPath);

        Assert.DoesNotContain(
            secretValue,
            json,
            StringComparison.Ordinal);

        SecretScanFinding finding =
            Assert.Single(
                result.Report!.Findings);

        Assert.Equal(
            "SecretPattern",
            finding.Category);

        Assert.Equal(
            "High",
            finding.Severity);

        Assert.Equal(
            "<redacted>",
            finding.Preview);

        Assert.DoesNotContain(
            secretValue,
            finding.File,
            StringComparison.Ordinal);
    }

